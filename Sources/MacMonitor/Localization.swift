import Foundation

enum AppLanguage {
    static var identifier: String {
        resolve(UserDefaults.standard.string(forKey: "appLanguage") ?? "system")
    }
    static func resolve(_ choice: String) -> String {
        if choice == "zh-Hans" || choice == "en" { return choice }
        return Locale.preferredLanguages.first?.lowercased().hasPrefix("zh") == true ? "zh-Hans" : "en"
    }
    static var isEnglish: Bool { identifier == "en" }
}

func translate(_ chinese: String, language: String) -> String { language == "en" ? (englishTranslations[chinese] ?? chinese) : chinese }
func tr(_ chinese: String) -> String { translate(chinese, language: AppLanguage.identifier) }
func bilingual(_ chinese: String, _ english: String) -> String { AppLanguage.isEnglish ? english : chinese }

